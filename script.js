let lang = 'vi';

function setLang(next) {
  lang = I18N[next] ? next : 'vi';
  const dict = I18N[lang];
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = dict[el.dataset.i18n]; });
  document.querySelectorAll('[data-i18n-attr]').forEach(el => {
    const [attr, key] = el.dataset.i18nAttr.split(':');
    el.setAttribute(attr, dict[key]);
  });
  try { localStorage.setItem('lang', lang); } catch {}
}

document.addEventListener('DOMContentLoaded', () => {
  let saved = null;
  try { saved = localStorage.getItem('lang'); } catch {}
  setLang(saved || 'vi');

  document.getElementById('lang-toggle').addEventListener('click', () => setLang(lang === 'vi' ? 'en' : 'vi'));

  document.querySelectorAll('[data-copy]').forEach(btn => {
    btn.addEventListener('click', async () => {
      try {
        await navigator.clipboard.writeText(btn.dataset.copy);
      } catch {
        return; // no clipboard (http / old browser): the number is visible next to the button
      }
      const label = btn.querySelector('[data-i18n]');
      label.textContent = I18N[lang].copied;
      setTimeout(() => { label.textContent = I18N[lang]['donate.copy']; }, 2000);
    });
  });
});
